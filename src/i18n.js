let currentLang = 'en'
let _rerenderHero = null
const FONTS_LOADED = new Set(['en'])

const FONT_URLS = {
  ar: 'https://fonts.googleapis.com/css2?family=Amiri:ital,wght@0,400;0,700;1,400&family=Cairo:wght@300;400;500;600&display=swap',
  he: 'https://fonts.googleapis.com/css2?family=Frank+Ruhl+Libre:wght@300;400;500;700&family=Heebo:wght@300;400;500;600&display=swap',
}

export function t(key) {
  return T[currentLang]?.[key] ?? T.en[key] ?? key
}

export function getCurrentLang() {
  return currentLang
}

export function initI18n(rerenderHero) {
  _rerenderHero = rerenderHero

  let saved = 'en'
  try { saved = localStorage.getItem('jr-lang') || 'en' } catch (_) {}
  if (!T[saved]) saved = 'en'

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => applyLang(btn.dataset.lang))
  })

  if (saved !== 'en') {
    applyLangImmediate(saved)
  } else {
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === 'en')
    })
  }
}

function applyLangImmediate(code) {
  if (!T[code]) return
  currentLang = code
  const dict = T[code]
  document.documentElement.lang = code
  document.documentElement.dir  = dict.dir
  updateDOM(dict, code)
  loadFonts(code)
  _rerenderHero?.()
}

export function applyLang(code) {
  if (!T[code] || code === currentLang) return
  currentLang = code
  const dict = T[code]

  document.body.style.transition = 'opacity 0.18s ease'
  document.body.style.opacity = '0'

  setTimeout(() => {
    document.documentElement.lang = code
    document.documentElement.dir  = dict.dir
    updateDOM(dict, code)
    loadFonts(code)
    _rerenderHero?.()
    try { localStorage.setItem('jr-lang', code) } catch (_) {}
    document.body.style.opacity = '1'
    setTimeout(() => { document.body.style.transition = '' }, 200)
  }, 180)
}

function updateDOM(dict, code) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const val = dict[el.dataset.i18n]
    if (val !== undefined) el.textContent = val
  })

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const val = dict[el.dataset.i18nHtml]
    if (val !== undefined) el.innerHTML = val
  })

  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const val = dict[el.dataset.i18nPh]
    if (val !== undefined) el.placeholder = val
  })

  const sel = document.getElementById('finterest')
  if (sel) {
    const keys = ['contact.interest.opt0','contact.interest.opt1','contact.interest.opt2','contact.interest.opt3','contact.interest.opt4','contact.interest.opt5']
    ;[...sel.options].forEach((opt, i) => {
      const val = dict[keys[i]]
      if (val !== undefined) opt.text = val
    })
  }

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === code)
  })
}

function loadFonts(code) {
  if (code === 'en' || FONTS_LOADED.has(code)) return
  const url = FONT_URLS[code]
  if (!url) return
  const link = document.createElement('link')
  link.rel = 'stylesheet'
  link.href = url
  document.head.appendChild(link)
  FONTS_LOADED.add(code)
}
